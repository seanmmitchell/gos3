package fs

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"strings"

	"go.etcd.io/bbolt"

	"github.com/seanmmitchell/gos3/internal/storage"
)

// Walks read entries in batches, each in its own short read transaction, and
// invoke the callback with no transaction open, so writers are never starved
// and callbacks may call back into (and mutate) the backend. Batches grow
// geometrically: the list helpers often stop after a single entry (on every
// common prefix), so the first batch is small, while long walks amortise the
// transaction cost.
//
// A batch also ends once it holds walkMaxBatchBytes of encoded records, so
// records with huge metadata (e.g. 10000 part checksums) cannot make a batch
// use unbounded memory.
const (
	walkMinBatch      = 16
	walkMaxBatch      = 1024
	walkMaxBatchBytes = 4 << 20
)

func nextBatch(n int) int { return min(n*2, walkMaxBatch) }

// callWalk invokes fn for each item; it reports stop=true when fn asked to
// stop (err nil) or failed (err non-nil).
func callWalk(ctx context.Context, items []storage.ObjectInfo, fn func(storage.ObjectInfo) error) (bool, error) {
	for _, it := range items {
		if err := fn(it); err != nil {
			if errors.Is(err, storage.ErrStopWalk) {
				return true, nil
			}
			return true, err
		}
	}
	if ctx != nil {
		if err := ctx.Err(); err != nil {
			return true, err
		}
	}
	return false, nil
}

// WalkObjects calls fn with the latest version of each key whose latest
// version is not a delete marker, in ascending byte-wise key order, for keys
// with the given prefix that are strictly greater than after.
func (b *Backend) WalkObjects(ctx context.Context, bucket, prefix, after string, fn func(storage.ObjectInfo) error) error {
	if fn == nil {
		return errors.New("fs: nil walk function")
	}
	if err := b.begin(ctx); err != nil {
		return err
	}
	pfx := []byte(prefix)
	// Seek position; the first entry equal to skip is skipped.
	start, skip := pfx, []byte(nil)
	if after >= prefix {
		start, skip = []byte(after), []byte(after)
	}
	var bucketID string
	batch := walkMinBatch
	for {
		items := make([]storage.ObjectInfo, 0, batch)
		done := true
		err := b.view(func(tx *bbolt.Tx) error {
			br, bb, err := loadBucket(tx, bucket)
			if err != nil {
				return err
			}
			if bucketID == "" {
				bucketID = br.ID
			} else if br.ID != bucketID {
				return fmt.Errorf("%w: %q was deleted", storage.ErrBucketNotFound, bucket)
			}
			c := bb.Bucket(subCurrent).Cursor()
			k, v := c.Seek(start)
			if skip != nil && k != nil && bytes.Equal(k, skip) {
				k, v = c.Next()
			}
			size := 0
			for ; k != nil && bytes.HasPrefix(k, pfx); k, v = c.Next() {
				if len(items) == batch || size > walkMaxBatchBytes {
					// Resume at k (inclusive) in the next batch.
					start, skip, done = bytes.Clone(k), nil, false
					return nil
				}
				size += len(k) + len(v)
				var rec versionRecord
				if err := decodeRecord(v, &rec); err != nil {
					return fmt.Errorf("object %q: %w", k, err)
				}
				items = append(items, rec.info(bucket, string(k), true))
			}
			return nil
		})
		if err != nil {
			return err
		}
		if stop, err := callWalk(ctx, items, fn); stop || err != nil {
			return err
		}
		if done {
			return nil
		}
		if b.closed.Load() {
			return ErrClosed
		}
		batch = nextBatch(batch)
	}
}

// WalkVersions calls fn for every version and delete marker of keys with the
// given prefix, keys ascending and newest version first within a key,
// starting after (keyMarker, versionIDMarker) per S3 ListObjectVersions
// semantics. If versionIDMarker is not a version of keyMarker, the walk
// resumes at the position the ID would occupy when it is an ID generated by
// this backend (e.g. a version deleted between pages), and otherwise after
// all versions of keyMarker.
func (b *Backend) WalkVersions(ctx context.Context, bucket, prefix, keyMarker, versionIDMarker string, fn func(storage.ObjectInfo) error) error {
	if fn == nil {
		return errors.New("fs: nil walk function")
	}
	if err := b.begin(ctx); err != nil {
		return err
	}
	pfx := escapeKey(nil, prefix)
	var (
		start, skip []byte
		resolve     bool // resolve versionIDMarker in the first transaction
	)
	switch {
	case keyMarker == "" || keyMarker < prefix:
		start = pfx
	case versionIDMarker == "":
		start = keyVersionsEnd(keyMarker)
	default:
		resolve = true
	}

	var (
		bucketID string
		prevKey  string
		havePrev bool
	)
	batch := walkMinBatch
	for {
		items := make([]storage.ObjectInfo, 0, batch)
		done := true
		err := b.view(func(tx *bbolt.Tx) error {
			br, bb, err := loadBucket(tx, bucket)
			if err != nil {
				return err
			}
			if bucketID == "" {
				bucketID = br.ID
			} else if br.ID != bucketID {
				return fmt.Errorf("%w: %q was deleted", storage.ErrBucketNotFound, bucket)
			}
			if resolve {
				resolve = false
				if vk, ok := versionPosition(bb, keyMarker, versionIDMarker); ok && len(keyMarker) <= maxKeyLen {
					start, skip = vk, vk
				} else {
					start = keyVersionsEnd(keyMarker)
				}
				if bytes.Compare(start, pfx) < 0 {
					start, skip = pfx, nil
				}
			}
			vers := bb.Bucket(subVersions)
			c := vers.Cursor()
			k, v := c.Seek(start)
			if skip != nil && k != nil && bytes.Equal(k, skip) {
				k, v = c.Next()
			}
			size := 0
			for ; k != nil && bytes.HasPrefix(k, pfx); k, v = c.Next() {
				if len(items) == batch || size > walkMaxBatchBytes {
					start, skip, done = bytes.Clone(k), nil, false
					return nil
				}
				size += len(k) + len(v)
				first := len(items) == 0
				key, _, ok := splitVersionKey(k)
				if !ok || !strings.HasPrefix(key, prefix) {
					return fmt.Errorf("%w: malformed version key %q", errCorrupt, k)
				}
				var latest bool
				switch {
				case havePrev && key == prevKey:
					latest = false
				case havePrev && !first:
					// Entries are visited contiguously within a
					// transaction, so the first entry of a new key is its
					// newest version.
					latest = true
				default:
					// First entry of the walk or of a batch: it may be in
					// the middle of a key's versions (versionIDMarker, or
					// versions added between batches).
					newest, _ := vers.Cursor().Seek(keyVersionsPrefix(key))
					latest = bytes.Equal(newest, k)
				}
				prevKey, havePrev = key, true
				var rec versionRecord
				if err := decodeRecord(v, &rec); err != nil {
					return fmt.Errorf("version of %q: %w", key, err)
				}
				items = append(items, rec.info(bucket, key, latest))
			}
			return nil
		})
		if err != nil {
			return err
		}
		if stop, err := callWalk(ctx, items, fn); stop || err != nil {
			return err
		}
		if done {
			return nil
		}
		if b.closed.Load() {
			return ErrClosed
		}
		batch = nextBatch(batch)
	}
}
