// Package memory implements an ephemeral, in-memory storage.Backend.
//
// Everything lives in Go maps and per-bucket ordered skip lists guarded by
// read/write mutexes, so the backend is safe for concurrent use. It is meant
// for tests, development and ephemeral deployments: all data is lost when
// the process exits.
//
// Design notes:
//   - Object data is stored as immutable byte slices; readers returned by
//     OpenObject are snapshots over the slice of the exact version opened and
//     are never affected by later writes or deletes.
//   - All metadata maps and slices are deep-copied on the way in and out, so
//     callers can never alias internal state.
//   - Keys of a bucket are kept in a skip list, so WalkObjects/WalkVersions
//     seek to prefix/marker in O(log n) and then step in O(1) per key.
//   - Walk callbacks run without any lock held (the walk collects small
//     batches under a read lock), so callbacks may call back into the backend,
//     including mutating it.
//   - Every version (including null versions and delete markers) is stamped
//     with a strictly increasing 64-bit sequence (derived from the wall clock
//     in nanoseconds) that orders versions newest-first. Generated version IDs
//     embed this stamp: 16 lowercase hex digits of the stamp followed by 8
//     random hex digits (24 characters, URL-safe, time-ordered, never "null").
//   - Imported versions (storage.VersionImporter, import.go) get a fresh
//     stamp but keep the version ID they had on their source backend, which
//     need not embed the stamp; lookups by such IDs fall back to scanning
//     the key's versions.
package memory

import (
	"bytes"
	"context"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"maps"
	"slices"
	"sort"
	"strconv"
	"sync"
	"time"
	"unicode/utf8"

	"github.com/seanmmitchell/gos3/internal/storage"
)

// ErrClosed is returned by every operation after Close.
var ErrClosed = errors.New("memory: backend closed")

// Backend is an in-memory storage.Backend. The zero value is not usable; use
// New.
type Backend struct {
	mu      sync.RWMutex // guards buckets and closed
	buckets map[string]*bucket
	closed  bool

	stampMu   sync.Mutex
	lastStamp uint64

	// now returns the current time; replaceable in tests.
	now func() time.Time
}

var (
	_ storage.Backend            = (*Backend)(nil)
	_ storage.ConditionalDeleter = (*Backend)(nil)
)
var (
	_ storage.ConditionalDeleter     = (*Backend)(nil)
	_ storage.UploadWalker           = (*Backend)(nil)
	_ storage.ConditionalMetaUpdater = (*Backend)(nil)
	_ storage.ConfigViewer           = (*Backend)(nil)
	_ storage.CheckedDeleter         = (*Backend)(nil)
)

// New returns an empty in-memory backend.
func New() *Backend {
	return &Backend{
		buckets: make(map[string]*bucket),
		now:     time.Now,
	}
}

// bucket holds the state of one bucket. All fields except name are guarded
// by mu.
type bucket struct {
	mu      sync.RWMutex
	info    storage.BucketInfo
	configs map[string][]byte
	objects *skipList[*object]
	uploads map[string]*upload
	// uploadOrder indexes uploads by uploadOrderKey (listing order).
	uploadOrder *skipList[*upload]
	// deleted is set when the bucket is removed (or the backend closed) so
	// that operations holding a stale pointer fail with ErrBucketNotFound.
	deleted bool
}

// object is the version history of one key. versions is ordered oldest
// first (ascending stamp), so the latest version is the last element. An
// object with no versions is removed from the bucket.
type object struct {
	versions []*version
	// imported counts the versions with a non-null imported version ID
	// (see import.go), whose IDs do not embed their stamp.
	imported int
}

// version is one stored object version or delete marker. data is immutable
// once committed.
type version struct {
	stamp        uint64
	id           string
	deleteMarker bool
	// imported is set for versions stored with a non-null version ID taken
	// from another backend.
	imported     bool
	meta         storage.ObjectMeta
	data         []byte // the content, or its compressed form (compression set)
	lastModified time.Time
	// compression is the algorithm data is compressed with ("" = none);
	// size is then the size of the content.
	compression string
	size        int64
}

func (o *object) latest() *version { return o.versions[len(o.versions)-1] }

// indexByStamp returns the index of the version with the given stamp, or -1.
func (o *object) indexByStamp(stamp uint64) int {
	i := sort.Search(len(o.versions), func(i int) bool { return o.versions[i].stamp >= stamp })
	if i < len(o.versions) && o.versions[i].stamp == stamp {
		return i
	}
	return -1
}

// indexByID returns the index of the version with the given ID, or -1.
// Generated IDs are found by binary search on the stamp they embed; "null"
// and imported IDs (which may have any shape, including that of an ID
// generated by another memory backend, whose embedded stamp means nothing
// here) by a linear scan, which only runs when the key has such versions.
func (o *object) indexByID(id string) int {
	if stamp, ok := stampFromVersionID(id); ok {
		if i := o.indexByStamp(stamp); i >= 0 && o.versions[i].id == id {
			return i
		}
	}
	if id != storage.NullVersionID && o.imported == 0 {
		return -1
	}
	for i := len(o.versions) - 1; i >= 0; i-- {
		if o.versions[i].id == id {
			return i
		}
	}
	return -1
}

func (o *object) removeAt(i int) *version {
	v := o.versions[i]
	o.versions = slices.Delete(o.versions, i, i+1)
	if v.imported {
		o.imported--
	}
	return v
}

// info builds a deep-copied ObjectInfo for version v of key.
func (v *version) info(bucketName, key string, isLatest bool) storage.ObjectInfo {
	oi := storage.ObjectInfo{
		Bucket:       bucketName,
		Key:          key,
		VersionID:    v.id,
		IsLatest:     isLatest,
		DeleteMarker: v.deleteMarker,
		Size:         int64(len(v.data)),
		LastModified: v.lastModified,
	}
	if !v.deleteMarker {
		oi.ObjectMeta = cloneMeta(v.meta)
		if v.compression != "" {
			oi.Size, oi.Compression, oi.StoredSize = v.size, v.compression, int64(len(v.data))
		}
	}
	return oi
}

// nextStamp returns a strictly increasing stamp based on the wall clock.
func (b *Backend) nextStamp() (uint64, time.Time) {
	now := b.now().UTC()
	b.stampMu.Lock()
	defer b.stampMu.Unlock()
	s := uint64(now.UnixNano())
	if now.UnixNano() < 0 || s <= b.lastStamp {
		s = b.lastStamp + 1
	}
	b.lastStamp = s
	return s, now
}

const (
	stampHexLen     = 16
	versionIDLength = stampHexLen + 8
)

// newVersionID formats a version ID embedding stamp.
func newVersionID(stamp uint64) string {
	var rnd [4]byte
	_, _ = rand.Read(rnd[:]) // crypto/rand.Read never fails (Go >= 1.24)
	buf := make([]byte, 0, versionIDLength)
	s := strconv.AppendUint(nil, stamp, 16)
	for i := len(s); i < stampHexLen; i++ {
		buf = append(buf, '0')
	}
	buf = append(buf, s...)
	buf = hex.AppendEncode(buf, rnd[:])
	return string(buf)
}

// stampFromVersionID extracts the stamp from an ID generated by
// newVersionID.
func stampFromVersionID(id string) (uint64, bool) {
	if len(id) != versionIDLength {
		return 0, false
	}
	for i := 0; i < len(id); i++ {
		c := id[i]
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return 0, false
		}
	}
	s, err := strconv.ParseUint(id[:stampHexLen], 16, 64)
	if err != nil {
		return 0, false
	}
	return s, true
}

// newUploadID returns a random, URL-safe upload ID.
func newUploadID() string {
	var rnd [24]byte
	_, _ = rand.Read(rnd[:])
	return hex.EncodeToString(rnd[:])
}

// --- clone helpers ---

func cloneMeta(m storage.ObjectMeta) storage.ObjectMeta {
	m.UserMeta = maps.Clone(m.UserMeta)
	m.Tags = maps.Clone(m.Tags)
	m.Checksums = maps.Clone(m.Checksums)
	m.PartSizes = slices.Clone(m.PartSizes)
	if m.PartChecksums != nil {
		pc := make([]map[string]string, len(m.PartChecksums))
		for i, c := range m.PartChecksums {
			pc[i] = maps.Clone(c)
		}
		m.PartChecksums = pc
	}
	return m
}

func clonePartMeta(m storage.PartMeta) storage.PartMeta {
	m.Checksums = maps.Clone(m.Checksums)
	return m
}

func cloneUpload(u storage.UploadInfo) storage.UploadInfo {
	u.Meta = cloneMeta(u.Meta)
	return u
}

// --- lookup helpers ---

func checkCtx(ctx context.Context) error {
	if ctx == nil {
		return nil
	}
	return ctx.Err()
}

// lookup returns the bucket named name without locking it.
func (b *Backend) lookup(name string) (*bucket, error) {
	b.mu.RLock()
	defer b.mu.RUnlock()
	if b.closed {
		return nil, ErrClosed
	}
	bk, ok := b.buckets[name]
	if !ok {
		return nil, fmt.Errorf("%w: %q", storage.ErrBucketNotFound, name)
	}
	return bk, nil
}

// rlockBucket returns the bucket read-locked. The caller must RUnlock it.
func (b *Backend) rlockBucket(ctx context.Context, name string) (*bucket, error) {
	if err := checkCtx(ctx); err != nil {
		return nil, err
	}
	bk, err := b.lookup(name)
	if err != nil {
		return nil, err
	}
	bk.mu.RLock()
	if bk.deleted {
		bk.mu.RUnlock()
		return nil, b.goneErr(name)
	}
	return bk, nil
}

// lockBucket returns the bucket write-locked. The caller must Unlock it.
func (b *Backend) lockBucket(ctx context.Context, name string) (*bucket, error) {
	if err := checkCtx(ctx); err != nil {
		return nil, err
	}
	bk, err := b.lookup(name)
	if err != nil {
		return nil, err
	}
	bk.mu.Lock()
	if bk.deleted {
		bk.mu.Unlock()
		return nil, b.goneErr(name)
	}
	return bk, nil
}

// goneErr is the error for a bucket pointer found to be deleted.
func (b *Backend) goneErr(name string) error {
	b.mu.RLock()
	closed := b.closed
	b.mu.RUnlock()
	if closed {
		return ErrClosed
	}
	return fmt.Errorf("%w: %q", storage.ErrBucketNotFound, name)
}

// relock re-acquires the write lock of a bucket pointer obtained earlier
// (by a writer) and verifies it still exists.
func (b *Backend) relock(ctx context.Context, bk *bucket) error {
	if err := checkCtx(ctx); err != nil {
		return err
	}
	bk.mu.Lock()
	if bk.deleted {
		name := bk.info.Name
		bk.mu.Unlock()
		return b.goneErr(name)
	}
	return nil
}

// --- buckets ---

// ListBuckets returns all buckets sorted by name.
func (b *Backend) ListBuckets(ctx context.Context) ([]storage.BucketInfo, error) {
	if err := checkCtx(ctx); err != nil {
		return nil, err
	}
	b.mu.RLock()
	defer b.mu.RUnlock()
	if b.closed {
		return nil, ErrClosed
	}
	out := make([]storage.BucketInfo, 0, len(b.buckets))
	for _, bk := range b.buckets {
		bk.mu.RLock()
		out = append(out, bk.info)
		bk.mu.RUnlock()
	}
	slices.SortFunc(out, func(a, c storage.BucketInfo) int {
		switch {
		case a.Name < c.Name:
			return -1
		case a.Name > c.Name:
			return 1
		}
		return 0
	})
	return out, nil
}

// CreateBucket creates a bucket. Any non-empty name is accepted (validation
// is the S3 layer's job); "" yields ErrInvalidName.
func (b *Backend) CreateBucket(ctx context.Context, name string, opts storage.CreateBucketOptions) error {
	if err := checkCtx(ctx); err != nil {
		return err
	}
	if name == "" || !utf8.ValidString(name) {
		return fmt.Errorf("%w: bucket %q", storage.ErrInvalidName, name)
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return ErrClosed
	}
	if _, ok := b.buckets[name]; ok {
		return fmt.Errorf("%w: %q", storage.ErrBucketExists, name)
	}
	info := storage.BucketInfo{
		Name:              name,
		CreatedAt:         b.now().UTC(),
		Region:            opts.Region,
		ObjectLockEnabled: opts.ObjectLockEnabled,
		Owner:             opts.Owner,
	}
	if opts.ObjectLockEnabled {
		info.Versioning = storage.VersioningEnabled
	}
	b.buckets[name] = &bucket{
		info:    info,
		configs: make(map[string][]byte),
		objects: newSkipList[*object](),
		uploads: make(map[string]*upload),

		uploadOrder: newSkipList[*upload](),
	}
	return nil
}

// GetBucket returns the bucket's info.
func (b *Backend) GetBucket(ctx context.Context, name string) (storage.BucketInfo, error) {
	bk, err := b.rlockBucket(ctx, name)
	if err != nil {
		return storage.BucketInfo{}, err
	}
	defer bk.mu.RUnlock()
	return bk.info, nil
}

// DeleteBucket removes an empty bucket and its configuration documents.
func (b *Backend) DeleteBucket(ctx context.Context, name string) error {
	if err := checkCtx(ctx); err != nil {
		return err
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return ErrClosed
	}
	bk, ok := b.buckets[name]
	if !ok {
		return fmt.Errorf("%w: %q", storage.ErrBucketNotFound, name)
	}
	bk.mu.Lock()
	defer bk.mu.Unlock()
	if bk.objects.Len() > 0 {
		return fmt.Errorf("%w: %q", storage.ErrBucketNotEmpty, name)
	}
	// In-progress multipart uploads do not keep a bucket alive (as on
	// AWS); they are aborted with it.
	bk.deleted = true
	bk.configs = nil
	clear(bk.uploads)
	bk.uploadOrder = newSkipList[*upload]()
	delete(b.buckets, name)
	return nil
}

// SetBucketVersioning changes the versioning state. Reverting a bucket that
// has been versioned to VersioningUnversioned is rejected.
func (b *Backend) SetBucketVersioning(ctx context.Context, name string, status storage.VersioningStatus) error {
	switch status {
	case storage.VersioningUnversioned, storage.VersioningEnabled, storage.VersioningSuspended:
	default:
		return fmt.Errorf("memory: invalid versioning status %q", status)
	}
	bk, err := b.lockBucket(ctx, name)
	if err != nil {
		return err
	}
	defer bk.mu.Unlock()
	if status == storage.VersioningUnversioned && bk.info.Versioning != storage.VersioningUnversioned {
		return errors.New("memory: a versioned bucket cannot become unversioned")
	}
	bk.info.Versioning = status
	return nil
}

// SetBucketObjectLock sets the bucket's object-lock flag.
func (b *Backend) SetBucketObjectLock(ctx context.Context, name string, enabled bool) error {
	bk, err := b.lockBucket(ctx, name)
	if err != nil {
		return err
	}
	defer bk.mu.Unlock()
	bk.info.ObjectLockEnabled = enabled
	return nil
}

// GetBucketConfig returns a copy of a configuration document.
func (b *Backend) GetBucketConfig(ctx context.Context, bucketName, key string) ([]byte, error) {
	bk, err := b.rlockBucket(ctx, bucketName)
	if err != nil {
		return nil, err
	}
	defer bk.mu.RUnlock()
	data, ok := bk.configs[key]
	if !ok {
		return nil, fmt.Errorf("%w: %s/%s", storage.ErrConfigNotFound, bucketName, key)
	}
	return bytes.Clone(data), nil
}

// ViewBucketConfig calls fn with a stored configuration document, without
// copying it, under the bucket's read lock (see storage.ConfigViewer).
func (b *Backend) ViewBucketConfig(ctx context.Context, bucketName, key string, fn func([]byte) error) error {
	bk, err := b.rlockBucket(ctx, bucketName)
	if err != nil {
		return err
	}
	defer bk.mu.RUnlock()
	data, ok := bk.configs[key]
	if !ok {
		return fmt.Errorf("%w: %s/%s", storage.ErrConfigNotFound, bucketName, key)
	}
	return fn(data)
}

// PutBucketConfig stores a copy of a configuration document.
func (b *Backend) PutBucketConfig(ctx context.Context, bucketName, key string, data []byte) error {
	if key == "" {
		return fmt.Errorf("%w: empty config key", storage.ErrInvalidName)
	}
	bk, err := b.lockBucket(ctx, bucketName)
	if err != nil {
		return err
	}
	defer bk.mu.Unlock()
	bk.configs[key] = append([]byte{}, data...)
	return nil
}

// DeleteBucketConfig removes a configuration document; it is idempotent.
func (b *Backend) DeleteBucketConfig(ctx context.Context, bucketName, key string) error {
	bk, err := b.lockBucket(ctx, bucketName)
	if err != nil {
		return err
	}
	defer bk.mu.Unlock()
	delete(bk.configs, key)
	return nil
}

// Close discards all data. Every subsequent operation returns ErrClosed;
// open readers keep working. Close is idempotent.
func (b *Backend) Close() error {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.closed {
		return nil
	}
	b.closed = true
	for _, bk := range b.buckets {
		bk.mu.Lock()
		bk.deleted = true
		bk.mu.Unlock()
	}
	b.buckets = nil
	return nil
}
