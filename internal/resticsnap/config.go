// Config is a bucket's snapshot schedule: the bucket configuration
// document storage.ConfigResticSnapshots (SnapshotConfig in the admin
// API), as PutConfig normalized it.
type Config struct {
	// Enabled schedules snapshots (manual runs work either way).
	Enabled bool `json:"enabled"`
	// Interval is the time between snapshots (1h-30d).
	Interval string `json:"interval"`
	// At is the UTC time of day ("HH:MM") of snapshots with intervals of
	// 24h or more ("": any time).
	At string `json:"at,omitempty"`
	// Consistent snapshots of versioned buckets hold the versions current
	// when the run started.
	Consistent bool `json:"consistent"`
	// Prefix limits the snapshot to the keys with this prefix.
	Prefix    string      `json:"prefix,omitempty"`
	Retention Retention   `json:"retention"`
	Target    Target      `json:"target"`
	Prune     PruneConfig `json:"prune"`
}

// Retention selects the snapshots kept (restic's forget policy, computed
// by gos3 in UTC); the newest snapshot is always kept.
type Retention struct {
	KeepLast    int    `json:"keepLast"`
	KeepHourly  int    `json:"keepHourly"`
	KeepDaily   int    `json:"keepDaily"`
	KeepWeekly  int    `json:"keepWeekly"`
	KeepMonthly int    `json:"keepMonthly"`
	KeepYearly  int    `json:"keepYearly"`
	KeepWithin  string `json:"keepWithin"`
}

// Target is the repository snapshots go to.
type Target struct {
	// Kind is TargetBucket or TargetBacking.
	Kind string `json:"kind"`
	// Backing names the backing of a TargetBacking repository.
	Backing string `json:"backing,omitempty"`
	// Repo is the name of the aux repository on Backing, generated by the
	// first PutConfig and kept by later ones.
	Repo string `json:"repo,omitempty"`
}

// Target kinds.
const (
	// TargetBucket is the bucket's own restic repository (fs buckets and
	// wrapped buckets of s3 backings).
	TargetBucket = "bucket"
	// TargetBacking is an aux repository on a backing.
	TargetBacking = "backing"
)

// PruneConfig schedules prunes of the repository after snapshots.
type PruneConfig struct {
	Enabled  bool   `json:"enabled"`
	Interval string `json:"interval"`
	// Default is set when the configuration did not choose Enabled: then
	// runs prune unless the bucket's restic archive scope is "all" when
	// they run (a prune's exclusive lock would stall its writes), and
	// Enabled shows what that gave when the configuration was stored. A
	// PUT with "default": true keeps following the scope.
	Default bool `json:"default,omitempty"`
}

// Defaults and bounds of a Config.
const (
	defaultInterval      = 24 * time.Hour
	minInterval          = time.Hour
	maxInterval          = 30 * 24 * time.Hour
	defaultPruneInterval = 7 * 24 * time.Hour
	maxPruneInterval     = 366 * 24 * time.Hour
	maxKeep              = 100000
	maxKeepWithin        = 100 * 366 * 24 * time.Hour
	maxPrefix            = 1024
	// repoPrefix starts generated aux repository names.
	repoPrefix = "snap-"
)

// defaultRetention is the retention of a configuration without one.
var defaultRetention = Retention{KeepLast: 7, KeepDaily: 7, KeepWeekly: 4, KeepMonthly: 12, KeepWithin: "0s"}

// interval returns c.Interval (validated).
func (c Config) interval() time.Duration {
	d, err := time.ParseDuration(c.Interval)
	if err != nil || d < minInterval {
		return defaultInterval
	}
	return d
}

// pruneInterval returns c.Prune.Interval (validated).
func (c Config) pruneInterval() time.Duration {
	d, err := time.ParseDuration(c.Prune.Interval)
	if err != nil || d < minInterval {
		return defaultPruneInterval
	}
	return d
}

// within returns r.KeepWithin (validated).
func (r Retention) within() time.Duration {
	d, err := time.ParseDuration(r.KeepWithin)
	if err != nil || d < 0 {
		return 0
	}
	return d
}

// configInput is a Config as clients send it: absent fields take their
// defaults.
type configInput struct {
	Enabled    *bool           `json:"enabled"`
	Interval   *string         `json:"interval"`
	At         *string         `json:"at"`
	Consistent *bool           `json:"consistent"`
	Prefix     *string         `json:"prefix"`
	Retention  *retentionInput `json:"retention"`
	Target     *Target         `json:"target"`
	Prune      *pruneInput     `json:"prune"`
}

type retentionInput struct {
	KeepLast    *int    `json:"keepLast"`
	KeepHourly  *int    `json:"keepHourly"`
	KeepDaily   *int    `json:"keepDaily"`
	KeepWeekly  *int    `json:"keepWeekly"`
	KeepMonthly *int    `json:"keepMonthly"`
	KeepYearly  *int    `json:"keepYearly"`
	KeepWithin  *string `json:"keepWithin"`
}

type pruneInput struct {
	Enabled  *bool   `json:"enabled"`
	Interval *string `json:"interval"`
	Default  *bool   `json:"default"`
}

// decodeStrict decodes the JSON object raw into v, refusing unknown fields
// and trailing data.
func decodeStrict(raw []byte, v any) error {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 || trimmed[0] != '{' {
		return errors.New("expected a JSON object")
	}
	dec := json.NewDecoder(bytes.NewReader(trimmed))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		return err
	}
	if _, err := dec.Token(); err != io.EOF {
		return errors.New("unexpected data after the JSON object")
	}
	return nil
}

// normalizeConfig validates in and fills in the defaults, except for the
// target (see normalizeTarget). pruneOn is the default of prune.enabled.
func normalizeConfig(in configInput, pruneOn bool) (Config, error) {
	c := Config{Enabled: true, Interval: formatDuration(defaultInterval), Consistent: true, Retention: defaultRetention,
		Prune: PruneConfig{Enabled: pruneOn, Interval: formatDuration(defaultPruneInterval), Default: true}}
	if in.Enabled != nil {
		c.Enabled = *in.Enabled
	}
	if in.Consistent != nil {
		c.Consistent = *in.Consistent
	}
	interval := defaultInterval
	if in.Interval != nil {
		d, err := time.ParseDuration(*in.Interval)
		if err != nil || d < minInterval || d > maxInterval {
			return Config{}, invalidSpec("interval %q: want a duration from 1h to 720h (30 days)", *in.Interval)
		}
		interval, c.Interval = d, formatDuration(d)
	}
	if in.At != nil && *in.At != "" {
		at, err := parseAt(*in.At)
		if err != nil {
			return Config{}, err
		}
		if interval < 24*time.Hour {
			return Config{}, invalidSpec("at needs an interval of 24h or more")
		}
		c.At = at
	}
	if in.Prefix != nil {
		if len(*in.Prefix) > maxPrefix {
			return Config{}, invalidSpec("prefix is longer than %d bytes", maxPrefix)
		}
		c.Prefix = *in.Prefix
	}
	if in.Retention != nil {
		r, err := normalizeRetention(*in.Retention)
		if err != nil {
			return Config{}, err
		}
		c.Retention = r
	}
	if in.Prune != nil {
		if in.Prune.Enabled != nil && (in.Prune.Default == nil || !*in.Prune.Default) {
			c.Prune.Enabled, c.Prune.Default = *in.Prune.Enabled, false
		}
		if in.Prune.Interval != nil {
			d, err := time.ParseDuration(*in.Prune.Interval)
			if err != nil || d < minInterval || d > maxPruneInterval {
				return Config{}, invalidSpec("prune.interval %q: want a duration from 1h to 8784h", *in.Prune.Interval)
			}
			c.Prune.Interval = formatDuration(d)
		}
	}
	return c, nil
}

// normalizeRetention validates a retention policy: missing rules are 0,
// and at least one rule must keep something.
func normalizeRetention(in retentionInput) (Retention, error) {
	var r Retention
	for _, f := range []struct {
		name string
		in   *int
		out  *int
	}{
		{"keepLast", in.KeepLast, &r.KeepLast}, {"keepHourly", in.KeepHourly, &r.KeepHourly},
		{"keepDaily", in.KeepDaily, &r.KeepDaily}, {"keepWeekly", in.KeepWeekly, &r.KeepWeekly},
		{"keepMonthly", in.KeepMonthly, &r.KeepMonthly}, {"keepYearly", in.KeepYearly, &r.KeepYearly},
	} {
		if f.in == nil {
			continue
		}
		if *f.in < 0 || *f.in > maxKeep {
			return Retention{}, invalidSpec("retention.%s %d: want 0 to %d", f.name, *f.in, maxKeep)
		}
		*f.out = *f.in
	}
	within := time.Duration(0)
	if in.KeepWithin != nil {
		d, err := time.ParseDuration(*in.KeepWithin)
		if err != nil || d < 0 || d > maxKeepWithin {
			return Retention{}, invalidSpec("retention.keepWithin %q: want a duration of 0s or more", *in.KeepWithin)
		}
		within = d
	}
	r.KeepWithin = formatDuration(within)
	if r.KeepLast+r.KeepHourly+r.KeepDaily+r.KeepWeekly+r.KeepMonthly+r.KeepYearly == 0 && within == 0 {
		return Retention{}, invalidSpec("retention keeps no snapshot besides the newest: set keepLast or another rule")
	}
	return r, nil
}

// parseAt validates a time of day "H:MM" or "HH:MM" and returns it as
// "HH:MM".
func parseAt(s string) (string, error) {
	h, m, ok := strings.Cut(s, ":")
	hour, herr := strconv.Atoi(h)
	minute, merr := strconv.Atoi(m)
	if !ok || herr != nil || merr != nil || len(h) < 1 || len(h) > 2 || len(m) != 2 ||
		hour < 0 || hour > 23 || minute < 0 || minute > 59 {
		return "", invalidSpec("at %q: want a UTC time of day HH:MM", s)
	}
	return fmt.Sprintf("%02d:%02d", hour, minute), nil
}

// atOffset returns the offset of the time of day c.At from midnight.
func (c Config) atOffset() (time.Duration, bool) {
	if c.At == "" {
		return 0, false
	}
	h, m, _ := strings.Cut(c.At, ":")
	hour, _ := strconv.Atoi(h)
	minute, _ := strconv.Atoi(m)
	return time.Duration(hour)*time.Hour + time.Duration(minute)*time.Minute, true
}

// formatDuration formats d compactly ("24h", "1h30m", "0s").
func formatDuration(d time.Duration) string {
	if d <= 0 {
		return "0s"
	}
	if d%time.Second != 0 {
		return d.String()
	}
	var b strings.Builder
	h, rest := d/time.Hour, d%time.Hour
	m, rest := rest/time.Minute, rest%time.Minute
	sec := rest / time.Second
	if h > 0 {
		fmt.Fprintf(&b, "%dh", h)
	}
	if m > 0 {
		fmt.Fprintf(&b, "%dm", m)
	}
	if sec > 0 {
		fmt.Fprintf(&b, "%ds", sec)
	}
	return b.String()
}

// parseStoredConfig parses a stored configuration document.
func parseStoredConfig(raw []byte) (Config, error) {
	var in configInput
	if err := decodeStrict(raw, &in); err != nil {
		return Config{}, invalidSpec("stored snapshot configuration: %v", err)
	}
	c, err := normalizeConfig(in, true)
	if err != nil {
		return Config{}, err
	}
	if in.Prune != nil && in.Prune.Enabled != nil {
		c.Prune.Enabled = *in.Prune.Enabled // as stored (defaulted or not)
	}
	if in.Target == nil {
		return Config{}, invalidSpec("stored snapshot configuration has no target")
	}
	t := *in.Target
	switch t.Kind {
	case TargetBucket:
		t.Backing, t.Repo = "", ""
	case TargetBacking:
		if t.Backing == "" || !validRepoName(t.Repo) {
			return Config{}, invalidSpec("stored snapshot configuration: invalid backing target")
		}
	default:
		return Config{}, invalidSpec("stored snapshot configuration: unknown target kind %q", t.Kind)
	}
	c.Target = t
	return c, nil
}

// validRepoName reports whether name is a valid aux repository name
// ([a-z0-9-]{1,64}).
func validRepoName(name string) bool {
	if name == "" || len(name) > 64 {
		return false
	}
	for i := 0; i < len(name); i++ {
		if c := name[i]; !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-') {
			return false
		}
	}
	return true
}

// newRepoName returns a new aux repository name: "snap-" and 16 random hex
// digits.
func newRepoName() string {
	var b [8]byte
	_, _ = rand.Read(b[:])
	return repoPrefix + hex.EncodeToString(b[:])
}

// Config returns the bucket's snapshot configuration document;
// storage.ErrConfigNotFound when it has none (storage.ErrBucketNotFound for
// unknown buckets).
func (s *Service) Config(ctx context.Context, bucket string) (json.RawMessage, error) {
	raw, err := s.router.GetBucketConfig(ctx, bucket, storage.ConfigResticSnapshots)
	if err != nil {
		return nil, err
	}
	if !json.Valid(raw) {
		return nil, fmt.Errorf("resticsnap: the snapshot configuration of bucket %q is not valid JSON", bucket)
	}
	return json.RawMessage(raw), nil
}

// loadConfig reads and parses the bucket's configuration.
func (s *Service) loadConfig(ctx context.Context, bucket string) (Config, error) {
	raw, err := s.router.GetBucketConfig(ctx, bucket, storage.ConfigResticSnapshots)
	if err != nil {
		return Config{}, err
	}
	return parseStoredConfig(raw)
}

// PutConfig validates doc (a SnapshotConfig: unknown fields, invalid
// values and unusable targets are errors wrapping jobs.ErrInvalidSpec),
// fills in the defaults, prepares the target repository (creating it) and
// stores the normalized configuration, which it returns.
//
// Without a target, the bucket's own repository is used when its backing
// keeps one, else an aux repository on the default backing when that can
// hold one; otherwise the target must name a backing. The aux repository
// name of a backing target is generated by the first PUT and kept by later
// ones (and after DeleteConfig), so that the snapshot chain continues; a
// client cannot choose it. prune.enabled defaults to false for buckets
// whose restic archive scope is "all" (a prune takes restic's exclusive
// lock, which stalls their writes), else to true.
func (s *Service) PutConfig(ctx context.Context, bucket string, doc json.RawMessage) (json.RawMessage, error) {
	if _, err := s.router.GetBucket(ctx, bucket); err != nil {
		return nil, err
	}
	var in configInput
	if err := decodeStrict(doc, &in); err != nil {
		return nil, invalidSpec("snapshot configuration: %v", err)
	}
	all, err := s.archiveScopeAll(ctx, bucket)
	if err != nil {
		return nil, err
	}
	cfg, err := normalizeConfig(in, !all)
	if err != nil {
		return nil, err
	}
	var stored *Target
	if old, err := s.loadConfig(ctx, bucket); err == nil {
		stored = &old.Target
	} else if !errors.Is(err, storage.ErrConfigNotFound) && !errors.Is(err, jobs.ErrInvalidSpec) {
		return nil, err
	}
	if cfg.Target, err = s.normalizeTarget(ctx, bucket, in.Target, stored); err != nil {
		return nil, err
	}
	info, _, err := s.resolve(ctx, bucket, cfg.Target, true)
	if err != nil {
		return nil, targetError(err)
	}
	raw, err := json.Marshal(cfg)
	if err != nil {
		return nil, err
	}
	if err := s.router.PutBucketConfig(ctx, bucket, storage.ConfigResticSnapshots, raw); err != nil {
		return nil, err
	}
	s.remember(bucket, cfg.Target, info.Repository)
	s.configChanged(bucket)
	s.log.Info("resticsnap: snapshot configuration stored", "bucket", bucket, "target", cfg.Target.Kind,
		"backing", cfg.Target.Backing, "repository", info.Repository, "enabled", cfg.Enabled)
	return raw, nil
}

// DeleteConfig removes the bucket's snapshot configuration: scheduling
// stops and the bucket's stage directory is removed; existing snapshots
// stay (and the aux repository name is remembered for a later PutConfig).
func (s *Service) DeleteConfig(ctx context.Context, bucket string) error {
	if err := s.router.DeleteBucketConfig(ctx, bucket, storage.ConfigResticSnapshots); err != nil {
		return err
	}
	s.configChanged(bucket)
	s.removeStage(bucket)
	return nil
}

// archiveScopeAll reports whether the bucket's restic archive scope is
// "all" (every write archived).
func (s *Service) archiveScopeAll(ctx context.Context, bucket string) (bool, error) {
	raw, err := s.router.GetBucketConfig(ctx, bucket, storage.ConfigEncryptionProvider)
	switch {
	case errors.Is(err, storage.ErrConfigNotFound):
		return false, nil
	case err != nil:
		return false, err
	}
	set, err := storage.ParseEncryptionSettings(raw)
	return err == nil && set.Scope == storage.EncryptionScopeAll, nil
}

// normalizeTarget returns the target of a PUT whose target is in (nil:
// the default), given the stored configuration's target (nil: none).
func (s *Service) normalizeTarget(ctx context.Context, bucket string, in, stored *Target) (Target, error) {
	repo := s.rememberedRepo(bucket)
	if stored != nil && stored.Repo != "" {
		repo = stored.Repo
	}
	if in == nil {
		return s.defaultTarget(ctx, bucket, repo)
	}
	t := *in
	if t.Kind == "" && t.Backing != "" {
		t.Kind = TargetBacking
	}
	switch t.Kind {
	case TargetBucket:
		if t.Backing != "" || t.Repo != "" {
			return Target{}, invalidSpec("target kind %q takes no backing or repo", TargetBucket)
		}
		return Target{Kind: TargetBucket}, nil
	case TargetBacking:
		if t.Backing == "" {
			return Target{}, invalidSpec("target kind %q needs a backing", TargetBacking)
		}
		if _, ok := s.router.BackingBackend(t.Backing); !ok {
			return Target{}, invalidSpec("unknown backing %q", t.Backing)
		}
		if t.Repo != "" && t.Repo != repo {
			return Target{}, invalidSpec("target.repo is chosen by the server and cannot be changed")
		}
		if repo == "" {
			repo = newRepoName()
		}
		return Target{Kind: TargetBacking, Backing: t.Backing, Repo: repo}, nil
	case "":
		return s.defaultTarget(ctx, bucket, repo)
	}
	return Target{}, invalidSpec("unknown target kind %q (want %q or %q)", t.Kind, TargetBucket, TargetBacking)
}

// defaultTarget returns the default target of bucket: its own repository
// when its backing keeps one, else an aux repository (named repo, or a new
// name) on the default backing when that can hold one.
func (s *Service) defaultTarget(ctx context.Context, bucket, repo string) (Target, error) {
	_, _, err := s.router.ResticRepository(ctx, bucket, false)
	switch {
	case err == nil || errors.Is(err, iofs.ErrNotExist):
		return Target{Kind: TargetBucket}, nil
	case !errors.Is(err, errors.ErrUnsupported):
		return Target{}, err
	}
	def := s.router.DefaultBacking()
	if be, ok := s.router.BackingBackend(def); ok {
		if h, ok := be.(restic.Host); ok {
			if repo == "" {
				repo = newRepoName()
			}
			_, _, err := h.ResticAuxRepository(ctx, repo, false)
			switch {
			case err == nil || errors.Is(err, iofs.ErrNotExist):
				return Target{Kind: TargetBacking, Backing: def, Repo: repo}, nil
			case !errors.Is(err, errors.ErrUnsupported):
				return Target{}, err
			}
		}
	}
	return Target{}, invalidSpec("bucket %q keeps no restic repository and the default backing %q cannot hold one: name a backing in the target", bucket, def)
}

// resolve returns the repository of target t of bucket, creating (and
// preparing) it with create. The info's Backing names the backing that
// holds it.
func (s *Service) resolve(ctx context.Context, bucket string, t Target, create bool) (restic.RepositoryInfo, restic.Location, error) {
	switch t.Kind {
	case TargetBucket:
		return s.router.ResticRepository(ctx, bucket, create)
	case TargetBacking:
		be, ok := s.router.BackingBackend(t.Backing)
		if !ok {
			return restic.RepositoryInfo{}, restic.Location{}, fmt.Errorf("%w %q", multi.ErrUnknownBacking, t.Backing)
		}
		h, ok := be.(restic.Host)
		if !ok {
			return restic.RepositoryInfo{}, restic.Location{}, fmt.Errorf("backing %q keeps no restic repositories: %w", t.Backing, errors.ErrUnsupported)
		}
		info, loc, err := h.ResticAuxRepository(ctx, t.Repo, create)
		info.Backing = t.Backing
		return info, loc, err
	}
	return restic.RepositoryInfo{}, restic.Location{}, fmt.Errorf("%w: unknown target kind %q", jobs.ErrInvalidSpec, t.Kind)
}

// targetError converts an error preparing a target: targets that cannot
// hold a repository are invalid specs.
func targetError(err error) error {
	if errors.Is(err, errors.ErrUnsupported) && !errors.Is(err, iofs.ErrNotExist) ||
		errors.Is(err, storage.ErrInvalidName) || errors.Is(err, multi.ErrUnknownBacking) {
		return fmt.Errorf("%w: snapshot target: %w", jobs.ErrInvalidSpec, err)
	}
	return err
}
